#!/usr/bin/env node
/**
 * Writes docs/automation-surface.md from the command manifest.
 *
 * The point of the file: an external driver (axbridge, a supervising agent, the
 * native E2E suite) should be able to learn what the app can be told to do
 * without taking a snapshot of a running window. Menu paths are derivable from
 * the manifest alone, so they are.
 *
 * Run with --check to fail instead of writing, which is how CI notices that
 * someone changed the commands and forgot to regenerate.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'docs', 'automation-surface.md');

// Must match CATEGORY_TITLES in src-tauri/src/menu.rs, including the order.
const CATEGORY_TITLES = [
  ['file', 'File'],
  ['git', 'Git'],
  ['agent', 'Agent'],
  ['canvas', 'Canvas'],
  ['view', 'View'],
  ['markdown', 'Markdown'],
];

const { commands } = JSON.parse(
  readFileSync(join(root, 'src', 'lib', 'commands', 'commands.json'), 'utf8')
);

const lines = [
  '<!-- Generated by scripts/generate-automation-surface.mjs. Do not edit. -->',
  '',
  '# Automation surface',
  '',
  'What AuricIDE can be told to do from outside, and how to address it.',
  '',
  '## Addressing rules',
  '',
  '- **Prefer the native menu.** A menu item is a real `AXMenuItem` with a real',
  '  title, so it stays addressable no matter how the webview renders. It also',
  '  works while a modal holds focus.',
  '- **Always pass `--exact`.** `--name` matches the accessible label as a',
  '  substring, and `axbridge` refuses an ambiguous target rather than guessing',
  '  which of several matches you meant.',
  '- **A greyed-out item is an answer.** Project-gated commands stay visible and',
  '  disabled when no project is open, so you can tell "not now" from "not here".',
  '- Menu items carry **no keyboard accelerators**. The shortcuts below are the',
  '  in-app ones; sending them with `axbridge key` needs the webview focused.',
  '',
  '## Commands',
  '',
  '| Menu path | Command id | Shortcut | Needs a project |',
  '| --- | --- | --- | --- |',
];

for (const [category, title] of CATEGORY_TITLES) {
  for (const cmd of commands.filter((c) => c.category === category)) {
    lines.push(
      `| \`${title} > ${cmd.label}\` | \`${cmd.id}\` | ${cmd.shortcut ? `\`${cmd.shortcut}\`` : '—'} | ${cmd.requiresProject ? 'yes' : 'no'} |`
    );
  }
}

const placed = new Set(CATEGORY_TITLES.map(([c]) => c));
const unplaced = commands.filter((c) => !placed.has(c.category));
if (unplaced.length > 0) {
  lines.push(
    '',
    '## Not reachable from the menu',
    '',
    'These have a category with no submenu, so they exist in the palette only.',
    'That is a bug in the manifest, not a design choice.',
    '',
    ...unplaced.map((c) => `- \`${c.id}\` (category \`${c.category}\`)`)
  );
}

lines.push(
  '',
  '## Example',
  '',
  '```bash',
  'axbridge menu com.auricide.ide "Agent > Start Agent"',
  'axbridge wait com.auricide.ide --window-title "(1) AuricIDE"   # an agent needs a human',
  '```',
  ''
);

const next = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // Missing counts as out of date.
  }
  if (current !== next) {
    console.error(
      'docs/automation-surface.md is out of date. Run: node scripts/generate-automation-surface.mjs'
    );
    process.exit(1);
  }
  console.log('automation surface up to date');
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT}`);
}
